-- 회원
CREATE TABLE member (
    member_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR2(100) NOT NULL,
    password    VARCHAR2(100) NOT NULL,
    nickname    VARCHAR2(30)  NOT NULL,
    role        VARCHAR2(10)  DEFAULT 'USER' NOT NULL,
    created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_member_email UNIQUE (email)
);

-- 시험 종류
CREATE TABLE exam (
    exam_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_code       VARCHAR2(20),
    name            VARCHAR2(100) NOT NULL,
    category        VARCHAR2(20)  NOT NULL,   -- NATIONAL / LANGUAGE / PRIVATE
    organizer       VARCHAR2(100),
    validity_months NUMBER(3),                -- NULL = 영구
    official_url    VARCHAR2(300),
    source          VARCHAR2(10)  DEFAULT 'MANUAL' NOT NULL,  -- API / MANUAL
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_exam_code UNIQUE (exam_code)
);

-- 회차별 일정
CREATE TABLE exam_schedule (
    schedule_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id      NUMBER        NOT NULL,
    round_name   VARCHAR2(50)  NOT NULL,
    stage        VARCHAR2(10)  NOT NULL,   -- WRITTEN / PRACTICAL / SINGLE
    reg_start    DATE,
    reg_end      DATE,
    exam_date    DATE,
    result_date  DATE,
    synced_at    TIMESTAMP,
    CONSTRAINT fk_schedule_exam FOREIGN KEY (exam_id) REFERENCES exam (exam_id),
    CONSTRAINT uk_schedule UNIQUE (exam_id, round_name, stage)
);
CREATE INDEX idx_schedule_reg_start ON exam_schedule (reg_start);
CREATE INDEX idx_schedule_exam_date ON exam_schedule (exam_date);

-- 구독
CREATE TABLE subscription (
    subscription_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       NUMBER    NOT NULL,
    exam_id         NUMBER    NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sub_member FOREIGN KEY (member_id) REFERENCES member (member_id),
    CONSTRAINT fk_sub_exam   FOREIGN KEY (exam_id)   REFERENCES exam (exam_id),
    CONSTRAINT uk_subscription UNIQUE (member_id, exam_id)
);

-- 내 스펙
CREATE TABLE member_spec (
    spec_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     NUMBER        NOT NULL,
    exam_id       NUMBER,                    -- 목록에 없는 스펙은 NULL
    custom_name   VARCHAR2(100),
    score         VARCHAR2(20),
    cert_number   VARCHAR2(50),
    acquired_date DATE          NOT NULL,
    expire_date   DATE,
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_spec_member FOREIGN KEY (member_id) REFERENCES member (member_id),
    CONSTRAINT fk_spec_exam   FOREIGN KEY (exam_id)   REFERENCES exam (exam_id),
    CONSTRAINT ck_spec_name CHECK (exam_id IS NOT NULL OR custom_name IS NOT NULL)
);
CREATE INDEX idx_spec_expire ON member_spec (expire_date);

-- 알림 설정
CREATE TABLE notification_setting (
    member_id        NUMBER PRIMARY KEY,
    email_enabled    NUMBER(1) DEFAULT 1 NOT NULL,
    telegram_enabled NUMBER(1) DEFAULT 0 NOT NULL,
    telegram_chat_id VARCHAR2(50),
    CONSTRAINT fk_noti_setting_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

-- 알림 발송 기록 (중복 발송 방지)
CREATE TABLE notification_log (
    log_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         NUMBER       NOT NULL,
    notification_type VARCHAR2(20) NOT NULL,  -- REG_START_D3, EXPIRE_D30 ...
    target_id         NUMBER       NOT NULL,  -- schedule_id 또는 spec_id
    status            VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
    retry_count       NUMBER(2)    DEFAULT 0 NOT NULL,
    sent_at           TIMESTAMP,
    created_at        TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_noti_log_member FOREIGN KEY (member_id) REFERENCES member (member_id),
    CONSTRAINT uk_noti_log UNIQUE (member_id, notification_type, target_id)
);